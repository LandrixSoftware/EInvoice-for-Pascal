def finish(lines):
    text = "\n".join(lines) + "\n"
    if any(ord(c) > 127 for c in text):
        fail("non-ASCII output")
    text = re.sub(r"\n +;\n", ";\n", text)
    return text.replace("\n", "\r\n").encode("ascii")


def main(argv):
    args = argv[1:]
    if any(a != "--check" for a in args):
        fail("unknown argument; usage: gen-syntaxmodel.py [--check]")
    check = "--check" in args
    data = json.load(io.open(os.path.join(HERE, "cii.json"), encoding="utf-8"))
    m = Model(data)
    outputs = {
        "source/LandrixEInvoiceCII.pas": finish(gen_model(m)),
        "source/LandrixEInvoiceCIIReader.pas": finish(gen_reader(m)),
        "source/LandrixEInvoiceCIIWriter.pas": finish(gen_writer(m)),
    }
    stale = []
    for rel, data_out in sorted(outputs.items()):
        path = os.path.join(ROOT, rel)
        if check:
            try:
                with open(path, "rb") as f:
                    current = f.read()
            except IOError:
                current = b""
            if current.replace(b"\r\n", b"\n") != data_out.replace(b"\r\n", b"\n"):
                stale.append(rel)
        else:
            with open(path, "wb") as f:
                f.write(data_out)
    if check:
        if stale:
            sys.stderr.write("gen-syntaxmodel: not up to date: %s\n" % ", ".join(stale))
            return 1
        print("gen-syntaxmodel: up to date")
        return 0
    print("gen-syntaxmodel: wrote %d units (%d classes, %d records)" % (
        len(outputs), len(m.classes()), len(m.records())))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
